static const char *SCRIPT =
    "var seen = 0;\n"
    "var imports = { env: {\n"
    "  log: function (v) { seen = v; },\n"
    "  zero: function () { return 1234; },\n"
    "  addtwo: function (a, b) { return a + b; }\n"
    "} };\n"
    "var inst = WebAssembly.instantiate(WebAssembly.compile(bytes), imports);\n"
    "var e = inst.exports;\n"
    "e.poke(8, 0x2a);\n"
    "var mem = new Uint8Array(e.memory.buffer);\n"
    "var r = [];\n"
    "r.push('add(40,2)   = ' + e.add(40, 2));\n"
    "r.push('mem[8]      = ' + mem[8]);\n"
    "r.push('peek(8)     = ' + e.peek(8));\n"
    "r.push('dbl(21.5)   = ' + e.dbl(21.5));\n"
    "r.push('callimp(7)  = ' + e.callimp(7) + ' (log saw ' + seen + ')');\n"
    "r.push('inc64(big)  = ' + String(e.inc64(9007199254740993n)));\n"
    "r.push('impzero()   = ' + e.impzero());\n"
    "r.push('impadd(20,22)= ' + e.impadd(20, 22));\n"
    "r.push('grow(1)     = ' + e.grow(1) + ', memory now ' + e.memory.buffer.byteLength + ' bytes');\n"
    "r.join('\\n')";

int main(void)
{
    JSRuntime *rt = JS_NewRuntime();
    JSContext *ctx;
    JSValue global, v;
    const char *s;

    if (!rt) {
        fprintf(stderr, "JS_NewRuntime failed\n");
        return 1;
    }
    ctx = JS_NewContext(rt);
    if (!ctx) {
        fprintf(stderr, "JS_NewContext failed\n");
        JS_FreeRuntime(rt);
        return 1;
    }

    /* 挂载 WebAssembly：一次调用，之后这个 context 就有全局 WebAssembly */
    if (JS_WhaleInstallWasm(ctx) < 0) {
        fprintf(stderr, "JS_WhaleInstallWasm failed\n");
        JS_FreeContext(ctx);
        JS_FreeRuntime(rt);
        return 1;
    }

    global = JS_GetGlobalObject(ctx);
    JS_SetPropertyStr(ctx, global, "bytes",
                      JS_NewArrayBufferCopy(ctx, MODULE, sizeof(MODULE)));
    JS_FreeValue(ctx, global);

    v = JS_Eval(ctx, SCRIPT, strlen(SCRIPT), "wasm_demo.js", JS_EVAL_TYPE_GLOBAL);
    if (JS_IsException(v)) {
        JSValue e = JS_GetException(ctx);
        s = JS_ToCString(ctx, e);
        fprintf(stderr, "eval failed: %s\n", s ? s : "?");
        if (s)
            JS_FreeCString(ctx, s);
        JS_FreeValue(ctx, e);
        JS_FreeValue(ctx, v);
        JS_FreeContext(ctx);
        JS_FreeRuntime(rt);
        return 1;
    }
    s = JS_ToCString(ctx, v);
    printf("WhaleJS %s + wasm3\n%s\n", JS_WhaleGetVersion(), s ? s : "?");
    if (s)
        JS_FreeCString(ctx, s);
    JS_FreeValue(ctx, v);

    JS_FreeContext(ctx);
    JS_FreeRuntime(rt);
    return 0;
}
